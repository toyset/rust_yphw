//! Модуль описывает трейты для сериалиации-десериализации транзакций.

use std::io::Result;

use crate::transaction::Transaction;

/// Трейт для десериализации транзакции
pub trait TransactionRead {
    /// Читает следующую транзакцию из источника данных.
    ///
    /// Возвращает `Ok(Some(Transaction))` при успешном чтении транзакции,
    /// `Ok(None)` при достижении конца данных, или ошибку ввода-вывода.
    fn read_next(&mut self) -> Result<Option<Transaction>>;
}

pub trait TransactionWrite {
    /// Записывает следующую транзакцию.
    ///
    /// # Аргументы
    /// * `transaction` - ссылка на записываемую транзакцию
    ///
    /// Возвращает `Ok(())` при успешной записи или ошибку ввода-вывода.
    fn write_next(&mut self, transaction: &Transaction) -> Result<()>;

    /// Сбрасывает буферы и гарантирует запись всех данных.
    ///
    /// Должен вызываться после завершения записи всех транзакций.
    fn flush(&mut self) -> Result<()>;
}
